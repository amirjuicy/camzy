import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage();
page.on('console', m=>{ if(m.type()==='error') console.log('ERR', m.text()); });
await page.goto('http://127.0.0.1:3000/contact.html', { waitUntil: 'networkidle' });
await page.waitForTimeout(2000);
console.log('selects:', await page.locator('select').count());
console.log('triggers:', await page.locator('.addr-province-trigger').count());
const sel = page.locator('select').first();
console.log('first select classes:', await sel.getAttribute('class'));
const trigger = sel.locator('..').locator('.addr-province-trigger');
await trigger.click();
await page.waitForTimeout(300);
const items = page.locator('.addr-province-menu__item');
console.log('menu items:', await items.count());
if (await items.count() > 1) await items.nth(1).click();
await page.waitForTimeout(300);
console.log('selected value:', await sel.inputValue());
await browser.close();