import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage();
page.on('console', m=>{ if(m.type()==='error') console.log('ERR', m.text()); });
await page.goto('http://127.0.0.1:3000/checkout-step2.html', { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(500);
console.log('html length body:', (await page.locator('body').innerHTML()).length);
console.log('has f-province:', (await page.locator('#f-province').count()));
await page.waitForTimeout(2000);
console.log('after wait f-province:', (await page.locator('#f-province').count()));
await browser.close();