import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage();
const errs=[];
page.on('console', m=>{ if(m.type()==='error') errs.push(m.text()); });
page.on('pageerror', e=>errs.push(String(e)));
await page.goto('http://127.0.0.1:3000/checkout-step2.html', { waitUntil: 'networkidle' });
await page.waitForTimeout(2000);
const provTrigger = page.locator('#f-province').locator('..').locator('.addr-province-trigger');
await provTrigger.click();
await page.waitForTimeout(300);
await page.locator('.addr-province-menu__item').filter({hasText:'تهران'}).click();
await page.waitForTimeout(500);
console.log('province value:', await page.locator('#f-province').inputValue());
const cityTrigger = page.locator('#f-city').locator('..').locator('.addr-province-trigger');
await cityTrigger.click();
await page.waitForTimeout(500);
const cityCount = await page.locator('.addr-province-menu__item').count();
console.log('city items:', cityCount);
if (cityCount>0) await page.locator('.addr-province-menu__item').nth(1).click();
await page.waitForTimeout(300);
console.log('city value:', await page.locator('#f-city').inputValue());
console.log('console errors:', errs.filter(e=>!e.includes('store-logo')).length, errs);
await browser.close();